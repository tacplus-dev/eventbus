package com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.grpc;

import com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.kafka.KafkaPublisher;
import com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.kafka.KafkaSubscriber;
import com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.kafka.TopicManager;

import com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.tacplus.types.services.eventbus.Eventbus;
import com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.tacplus.types.services.eventbus.AdminGrpc;
import com.gitlab.secondstarcavalier.controlplane.cavalier.services.eventbus.tacplus.types.libs.trace.Trace;
import com.google.protobuf.Empty;
import com.google.protobuf.Timestamp;
import io.grpc.Status;
import io.grpc.stub.StreamObserver;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.util.List;

/**
 * gRPC implementation for EventBusService control RPCs.
 * Typed per-topic Publish/Subscribe RPCs are generated by the Maven plugin
 * and wired into this service at build time.
 */
public class EventBusServiceImpl extends AdminGrpc.AdminImplBase {

	private static final Logger logger = LoggerFactory.getLogger(EventBusServiceImpl.class);
	private final TopicManager topicManager;
	private final KafkaPublisher publisher;
	private final KafkaSubscriber subscriber;

	public EventBusServiceImpl(TopicManager topicManager, KafkaPublisher publisher, KafkaSubscriber subscriber) {
		this.topicManager = topicManager;
		this.publisher = publisher;
		this.subscriber = subscriber;
	}

	// -----------------------------------------------------------------------
	// Topic admin
	// -----------------------------------------------------------------------

	@Override
	public void listTopics(Trace.TraceRequest request, StreamObserver<Eventbus.ListTopicsResponse> responseObserver) {
		try {
			List<TopicManager.TopicInfo> topics = topicManager.listTopics();

			Eventbus.ListTopicsResponse.Builder builder = Eventbus.ListTopicsResponse.newBuilder();
			for (TopicManager.TopicInfo info : topics) {
				builder.addTopics(toProto(info));
			}

			responseObserver.onNext(builder.build());
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to list topics", e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to list topics: " + e.getMessage())
					.asRuntimeException());
		}
	}

	@Override
	public void getTopicInfo(Eventbus.TopicInfoRequest request,
			StreamObserver<Eventbus.TopicInfo> responseObserver) {
		try {
			TopicManager.TopicInfo info = topicManager.getTopicInfo(request.getTopic());
			responseObserver.onNext(toProto(info));
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to get topic info for {}", request.getTopic(), e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to get topic info: " + e.getMessage())
					.asRuntimeException());
		}
	}

	@Override
	public void deleteTopic(Eventbus.DeleteTopicRequest request,
			StreamObserver<Empty> responseObserver) {
		try {
			topicManager.deleteTopic(request.getTopic());
			responseObserver.onNext(Empty.getDefaultInstance());
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to delete topic {}", request.getTopic(), e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to delete topic: " + e.getMessage())
					.asRuntimeException());
		}
	}

	@Override
	public void alterTopicConfig(Eventbus.AlterTopicConfigRequest request,
			StreamObserver<Eventbus.TopicInfo> responseObserver) {
		try {
			TopicManager.TopicInfo info = topicManager.alterTopicConfig(
					request.getTopic(), request.getRetentionMs(), request.getPartitionCount());
			responseObserver.onNext(toProto(info));
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to alter topic config for {}", request.getTopic(), e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to alter topic config: " + e.getMessage())
					.asRuntimeException());
		}
	}

	// -----------------------------------------------------------------------
	// Consumer group admin
	// -----------------------------------------------------------------------

	@Override
	public void getConsumerGroupLag(Eventbus.ConsumerGroupRequest request,
			StreamObserver<Eventbus.ConsumerGroupInfo> responseObserver) {
		try {
			TopicManager.ConsumerGroupInfo info = topicManager.getConsumerGroupLag(request.getGroupId());
			responseObserver.onNext(toProto(info));
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to get consumer group lag for {}", request.getGroupId(), e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to get consumer group lag: " + e.getMessage())
					.asRuntimeException());
		}
	}

	@Override
	public void listConsumerGroups(Trace.TraceRequest request,
			StreamObserver<Eventbus.ListConsumerGroupsResponse> responseObserver) {
		try {
			List<TopicManager.ConsumerGroupInfo> groups = topicManager.listConsumerGroups();
			Eventbus.ListConsumerGroupsResponse.Builder builder = Eventbus.ListConsumerGroupsResponse.newBuilder();
			for (TopicManager.ConsumerGroupInfo info : groups) {
				builder.addGroups(toProto(info));
			}
			responseObserver.onNext(builder.build());
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to list consumer groups", e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to list consumer groups: " + e.getMessage())
					.asRuntimeException());
		}
	}

	@Override
	public void resetConsumerGroupOffsets(Eventbus.ResetConsumerGroupOffsetsRequest request,
			StreamObserver<Empty> responseObserver) {
		try {
			KafkaSubscriber.SeekMode mode;
			long value = 0;

			// AGENT : TODO : Convert switch to rule switch

			switch (request.getResetToCase()) {
				case OFFSET:
					mode = KafkaSubscriber.SeekMode.OFFSET;
					value = request.getOffset();
					break;
				case TIMESTAMP:
					mode = KafkaSubscriber.SeekMode.TIMESTAMP;
					Timestamp ts = request.getTimestamp();
					value = ts.getSeconds() * 1000 + ts.getNanos() / 1_000_000;
					break;
				case TO_LATEST:
					mode = KafkaSubscriber.SeekMode.LATEST;
					break;
				case TO_EARLIEST:
					mode = KafkaSubscriber.SeekMode.EARLIEST;
					break;
				default:
					responseObserver.onError(Status.INVALID_ARGUMENT
							.withDescription("reset_to is required")
							.asRuntimeException());
					return;
			}

			topicManager.resetConsumerGroupOffsets(
					request.getGroupId(), request.getTopic(), mode, value);
			responseObserver.onNext(Empty.getDefaultInstance());
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to reset consumer group offsets for {}", request.getGroupId(), e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to reset offsets: " + e.getMessage())
					.asRuntimeException());
		}
	}

	@Override
	public void deleteConsumerGroup(Eventbus.ConsumerGroupRequest request,
			StreamObserver<Empty> responseObserver) {
		try {
			topicManager.deleteConsumerGroup(request.getGroupId());
			responseObserver.onNext(Empty.getDefaultInstance());
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to delete consumer group {}", request.getGroupId(), e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to delete consumer group: " + e.getMessage())
					.asRuntimeException());
		}
	}

	// -----------------------------------------------------------------------
	// Cluster health
	// -----------------------------------------------------------------------

	@Override
	public void getClusterHealth(Trace.TraceRequest request,
			StreamObserver<Eventbus.ClusterHealthResponse> responseObserver) {
		try {
			TopicManager.ClusterHealth health = topicManager.getClusterHealth();

			Eventbus.ClusterHealthResponse.Builder builder = Eventbus.ClusterHealthResponse.newBuilder()
					.setBrokerCount(health.brokerCount())
					.setControllerId(health.controllerId());

			for (TopicManager.BrokerInfo broker : health.brokers()) {
				builder.addBrokers(Eventbus.BrokerInfo.newBuilder()
						.setId(broker.id())
						.setHost(broker.host())
						.setPort(broker.port())
						.setIsController(broker.isController())
						.build());
			}

			responseObserver.onNext(builder.build());
			responseObserver.onCompleted();
		} catch (Exception e) {
			logger.error("Failed to get cluster health", e);
			responseObserver.onError(Status.INTERNAL
					.withDescription("Failed to get cluster health: " + e.getMessage())
					.asRuntimeException());
		}
	}

	// -----------------------------------------------------------------------
	// Accessors for generated typed RPC handlers
	// -----------------------------------------------------------------------

	public KafkaPublisher getPublisher() {
		return publisher;
	}

	public KafkaSubscriber getSubscriber() {
		return subscriber;
	}

	public TopicManager getTopicManager() {
		return topicManager;
	}

	// -----------------------------------------------------------------------
	// Proto converters
	// -----------------------------------------------------------------------

	private static Eventbus.TopicInfo toProto(TopicManager.TopicInfo info) {
		Eventbus.TopicInfo.Builder b = Eventbus.TopicInfo.newBuilder()
				.setName(info.name())
				.setPartitionCount(info.partitionCount())
				.setRetentionMs(info.retentionMs());
		info.earliestOffsets().forEach(b::putEarliestOffsets);
		info.latestOffsets().forEach(b::putLatestOffsets);
		return b.build();
	}

	private static Eventbus.ConsumerGroupInfo toProto(TopicManager.ConsumerGroupInfo info) {
		Eventbus.ConsumerGroupInfo.Builder b = Eventbus.ConsumerGroupInfo.newBuilder()
				.setGroupId(info.groupId())
				.setState(info.state())
				.setTotalLag(info.totalLag());

		for (TopicManager.PartitionLag pl : info.partitionLags()) {
			b.addPartitions(Eventbus.PartitionLag.newBuilder()
					.setTopic(pl.topic())
					.setPartition(pl.partition())
					.setCommittedOffset(pl.committedOffset())
					.setEndOffset(pl.endOffset())
					.setLag(pl.lag())
					.build());
		}

		return b.build();
	}
}
