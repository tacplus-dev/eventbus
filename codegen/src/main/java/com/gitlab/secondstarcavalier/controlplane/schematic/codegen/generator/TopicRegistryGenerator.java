package com.gitlab.secondstarcavalier.controlplane.schematic.codegen.generator;

import com.gitlab.secondstarcavalier.controlplane.schematic.codegen.TopicDiscovery.TopicField;
import com.gitlab.secondstarcavalier.controlplane.schematic.codegen.StringUtils;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates a topic registry used internally by the event-bus server
 * to map Kafka topic names to their protobuf types. This is a server-side
 * implementation detail — clients derive topic names from proto annotations
 * at build time via their own language's codegen.
 */
public class TopicRegistryGenerator {

    private final Path outputDir;
    private final String packageBase;

    public TopicRegistryGenerator(Path outputDir, String packageBase) {
        this.outputDir = outputDir;
        this.packageBase = packageBase;
    }

    /**
     * Derives the hand-written service package from the model package.
     * "com.example.eventbus.model" → "com.example.eventbus"
     */
    private String servicePackage() {
        if (packageBase.endsWith(".model")) {
            return packageBase.substring(0, packageBase.length() - ".model".length());
        }
        return packageBase;
    }

    public void generate(List<TopicField> topics) throws IOException {
        String svcPkg = servicePackage();
        StringBuilder sb = new StringBuilder();
        sb.append("// CODE GENERATED by eventbus-codegen-plugin — DO NOT EDIT\n");
        sb.append("package ").append(svcPkg).append(".generated;\n\n");

        sb.append("/**\n");
        sb.append(" * Internal server-side registry mapping Kafka topic names to proto types.\n");
        sb.append(" * Topic names follow the convention: {package_path}.{proto_package}.{StateRoot}.{FieldPascal}\n");
        sb.append(" * and are derivable from proto annotations in any language.\n");
        sb.append(" */\n");
        sb.append("public final class TopicRegistry {\n");
        sb.append("    private TopicRegistry() {}\n\n");

        for (TopicField topic : topics) {
            String rpcPrefix = topic.getStateName() + topic.getFieldPascal();
            String constName = toConstName(rpcPrefix);

            sb.append("    // Source: ").append(topic.getFieldType())
              .append(" (").append(topic.getStatePackage()).append(")\n");
            sb.append("    public static final String TOPIC_").append(constName)
              .append(" = \"").append(topic.getTopicName()).append("\";\n\n");
        }

        sb.append("}\n");

        Path outDir = outputDir.resolve("src/main/java")
                .resolve(svcPkg.replace('.', '/'))
                .resolve("generated");
        Files.createDirectories(outDir);
        Files.writeString(outDir.resolve("TopicRegistry.java"), sb.toString());
    }

    private static String toConstName(String pascalCase) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < pascalCase.length(); i++) {
            char c = pascalCase.charAt(i);
            if (Character.isUpperCase(c) && i > 0) {
                sb.append('_');
            }
            sb.append(Character.toUpperCase(c));
        }
        return sb.toString();
    }
}
