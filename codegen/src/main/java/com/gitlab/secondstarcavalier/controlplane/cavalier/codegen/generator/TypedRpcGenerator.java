package com.gitlab.secondstarcavalier.controlplane.cavalier.codegen.generator;

import com.gitlab.secondstarcavalier.controlplane.cavalier.codegen.TopicDiscovery.TopicField;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.ArrayList;

/**
 * Generates TypedEventBusBindings.java — programmatic gRPC MethodDescriptors
 * and a bindAll() method that wires typed Publish/Subscribe RPCs for each
 * discovered eventbus topic.
 *
 * The generated code uses PublishHandler and SubscribeHandler (non-generated
 * generic helpers) with per-topic proto type + Kafka topic name.
 *
 * Typed RPCs are registered as a separate gRPC service
 * ("eventbus.EventBusTypedService") alongside the hand-written control RPCs.
 */
public class TypedRpcGenerator {

    private final Path outputDir;
    private final String packageBase;

    public TypedRpcGenerator(Path outputDir, String packageBase) {
        this.outputDir = outputDir;
        this.packageBase = packageBase;
    }

    /**
     * Derives the hand-written service package from the model package.
     * "com.example.eventbus.model" → "com.example.eventbus"
     */
    private String servicePackage() {
        if (packageBase.endsWith(".model")) {
            return packageBase.substring(0, packageBase.length() - ".model".length());
        }
        return packageBase;
    }

    public void generate(List<TopicField> topics) throws IOException {
        String svcPkg = servicePackage();
        StringBuilder sb = new StringBuilder();
        sb.append("// CODE GENERATED by eventbus-codegen-plugin — DO NOT EDIT\n");
        sb.append("package ").append(svcPkg).append(".generated;\n\n");

        // Imports
        sb.append("import com.google.protobuf.MessageLite;\n");
        sb.append("import io.grpc.MethodDescriptor;\n");
        sb.append("import io.grpc.ServerServiceDefinition;\n");
        sb.append("import io.grpc.Status;\n");
        sb.append("import io.grpc.protobuf.ProtoUtils;\n");
        sb.append("import io.grpc.stub.ServerCalls;\n");
        sb.append("import io.grpc.stub.StreamObserver;\n");
        sb.append("import java.util.Arrays;\n");
        sb.append("import java.util.HashSet;\n");
        sb.append("import java.util.Set;\n");
        sb.append("import java.util.function.Supplier;\n\n");

        // Hand-written service code (under service package, not model)
        sb.append("import ").append(svcPkg).append(".kafka.KafkaPublisher;\n");
        sb.append("import ").append(svcPkg).append(".kafka.KafkaSubscriber;\n");
        sb.append("import ").append(svcPkg).append(".kafka.TopicManager;\n");
        sb.append("import ").append(svcPkg).append(".grpc.PublishHandler;\n");
        sb.append("import ").append(svcPkg).append(".grpc.SubscribeHandler;\n");
        // Proto types under model package
        sb.append("import ").append(packageBase).append(".types.services.eventbus.Eventbus;\n\n");

        // Import each topic's proto outer class (messages are nested inside)
        Set<String> importedClasses = new LinkedHashSet<>();
        for (TopicField topic : topics) {
            importedClasses.add(topic.getJavaOuterClassImport(packageBase));
        }
        for (String cls : importedClasses) {
            sb.append("import ").append(cls).append(";\n");
        }
        sb.append("\n");

        sb.append("/**\n");
        sb.append(" * Generated typed Publish/Subscribe gRPC bindings for eventbus topics.\n");
        sb.append(" * Register with the gRPC server via {@link #bindAll}.\n");
        sb.append(" */\n");
        sb.append("public final class TypedEventBusBindings {\n");
        sb.append("    private TypedEventBusBindings() {}\n\n");

        sb.append("    private static final String SERVICE_NAME = \"eventbus.EventBusTypedService\";\n\n");

        // Method descriptors for each topic
        for (TopicField topic : topics) {
            String rpcPrefix = topic.getStateName() + topic.getFieldPascal();
            String constName = toConstName(rpcPrefix);
            String qualifiedType = topic.getJavaQualifiedType();

            // Publish method descriptor
            sb.append("    public static final MethodDescriptor<").append(qualifiedType)
              .append(", Eventbus.PublishResponse>\n");
            sb.append("        PUBLISH_").append(constName).append(" = MethodDescriptor\n");
            sb.append("            .<").append(qualifiedType).append(", Eventbus.PublishResponse>newBuilder()\n");
            sb.append("            .setType(MethodDescriptor.MethodType.BIDI_STREAMING)\n");
            sb.append("            .setFullMethodName(SERVICE_NAME + \"/Publish").append(rpcPrefix).append("\")\n");
            sb.append("            .setRequestMarshaller(ProtoUtils.marshaller(")
              .append(qualifiedType).append(".getDefaultInstance()))\n");
            sb.append("            .setResponseMarshaller(ProtoUtils.marshaller(Eventbus.PublishResponse.getDefaultInstance()))\n");
            sb.append("            .build();\n\n");

            // Subscribe method descriptor
            sb.append("    public static final MethodDescriptor<Eventbus.SubscribeRequest, ")
              .append(qualifiedType).append(">\n");
            sb.append("        SUBSCRIBE_").append(constName).append(" = MethodDescriptor\n");
            sb.append("            .<Eventbus.SubscribeRequest, ").append(qualifiedType).append(">newBuilder()\n");
            sb.append("            .setType(MethodDescriptor.MethodType.BIDI_STREAMING)\n");
            sb.append("            .setFullMethodName(SERVICE_NAME + \"/Subscribe").append(rpcPrefix).append("\")\n");
            sb.append("            .setRequestMarshaller(ProtoUtils.marshaller(Eventbus.SubscribeRequest.getDefaultInstance()))\n");
            sb.append("            .setResponseMarshaller(ProtoUtils.marshaller(")
              .append(qualifiedType).append(".getDefaultInstance()))\n");
            sb.append("            .build();\n\n");
        }

        // bindAll method
        sb.append("    /**\n");
        sb.append("     * Creates a ServerServiceDefinition with all typed Publish/Subscribe RPCs.\n");
        sb.append("     * Register this alongside EventBusServiceImpl on the gRPC server.\n");
        sb.append("     */\n");
        sb.append("    public static ServerServiceDefinition bindAll(\n");
        sb.append("            KafkaPublisher publisher, KafkaSubscriber subscriber, TopicManager topicManager) {\n\n");
        sb.append("        ServerServiceDefinition.Builder svc = ServerServiceDefinition.builder(SERVICE_NAME);\n\n");

        for (TopicField topic : topics) {
            String rpcPrefix = topic.getStateName() + topic.getFieldPascal();
            String constName = toConstName(rpcPrefix);
            String qualifiedType = topic.getJavaQualifiedType();

            // Publish binding
            sb.append("        // ").append(topic.getTopicName()).append("\n");
            sb.append("        svc.addMethod(PUBLISH_").append(constName).append(",\n");
            sb.append("            ServerCalls.asyncBidiStreamingCall(\n");
            sb.append("                (StreamObserver<Eventbus.PublishResponse> resp) ->\n");
            sb.append("                    new PublishHandler<>(TopicRegistry.TOPIC_").append(constName)
              .append(", publisher, topicManager, resp,\n");
            if (topic.hasEmailField()) {
                // C2S topic: stamp the caller's email from the JWT onto the proto message
                sb.append("                        (msg, email) -> msg.toBuilder().setEmail(email).build())));\n\n");
            } else {
                // S2S/internal topic: no identity stamping needed
                sb.append("                        null)));\n\n");
            }

            // Subscribe binding
            sb.append("        svc.addMethod(SUBSCRIBE_").append(constName).append(",\n");
            sb.append("            ServerCalls.asyncBidiStreamingCall(\n");
            sb.append("                (StreamObserver<").append(qualifiedType).append("> resp) ->\n");
            sb.append("                    new SubscribeHandler<>(subscriber, TopicRegistry.TOPIC_")
              .append(constName).append(", resp,\n");
            sb.append("                        ").append(qualifiedType).append("::parseFrom)));\n\n");
        }

        sb.append("        return svc.build();\n");
        sb.append("    }\n\n");

        // addRemainingLazy method — lazy null-check version that skips specified descriptors.
        // EventBusHandler calls this to auto-include any new topics without code changes.
        sb.append("    /**\n");
        sb.append("     * Adds lazy Publish/Subscribe bindings for all topics EXCEPT those whose\n");
        sb.append("     * method descriptors appear in {@code skip}. Kafka clients are resolved\n");
        sb.append("     * via suppliers at call time; returns UNAVAILABLE if not yet initialized.\n");
        sb.append("     *\n");
        sb.append("     * <p>Pass the descriptors for topics that need special handling\n");
        sb.append("     * (e.g. trace dispatch) to exclude them from this auto-registration:\n");
        sb.append("     * <pre>{@code\n");
        sb.append("     *   TypedEventBusBindings.addRemainingLazy(svc,\n");
        sb.append("     *       () -> publisher, () -> subscriber, () -> topicManager,\n");
        sb.append("     *       PUBLISH_AGENTIC_CODE_EVENT_BUS_EVENT_STREAM,\n");
        sb.append("     *       SUBSCRIBE_AGENTIC_CODE_EVENT_BUS_EVENT_STREAM);\n");
        sb.append("     * }</pre>\n");
        sb.append("     */\n");
        sb.append("    @SuppressWarnings(\"unchecked\")\n");
        sb.append("    public static void addRemainingLazy(\n");
        sb.append("            ServerServiceDefinition.Builder svc,\n");
        sb.append("            Supplier<KafkaPublisher> publisher,\n");
        sb.append("            Supplier<KafkaSubscriber> subscriber,\n");
        sb.append("            Supplier<TopicManager> topicManager,\n");
        sb.append("            MethodDescriptor<?, ?>... skip) {\n");
        sb.append("        Set<MethodDescriptor<?, ?>> skipSet = new HashSet<>(Arrays.asList(skip));\n\n");

        for (TopicField topic : topics) {
            String rpcPrefix = topic.getStateName() + topic.getFieldPascal();
            String constName = toConstName(rpcPrefix);
            String qualifiedType = topic.getJavaQualifiedType();

            sb.append("        // ").append(topic.getTopicName()).append("\n");
            sb.append("        if (!skipSet.contains(PUBLISH_").append(constName).append(")) {\n");
            sb.append("            svc.addMethod(PUBLISH_").append(constName).append(",\n");
            sb.append("                ServerCalls.asyncBidiStreamingCall(\n");
            sb.append("                    (StreamObserver<Eventbus.PublishResponse> resp) -> {\n");
            sb.append("                        KafkaPublisher pub = publisher.get();\n");
            sb.append("                        TopicManager tm = topicManager.get();\n");
            sb.append("                        if (pub == null || tm == null) {\n");
            sb.append("                            resp.onError(Status.UNAVAILABLE.withDescription(\"Kafka not yet initialized\").asRuntimeException());\n");
            sb.append("                            return noOpObserver();\n");
            sb.append("                        }\n");
            sb.append("                        return new PublishHandler<>(TopicRegistry.TOPIC_").append(constName)
              .append(", pub, tm, resp,\n");
            if (topic.hasEmailField()) {
                sb.append("                                (msg, email) -> msg.toBuilder().setEmail(email).build(),\n");
            } else {
                sb.append("                                null,\n");
            }
            sb.append("                                null, null);\n");
            sb.append("                    }));\n");
            sb.append("        }\n");

            sb.append("        if (!skipSet.contains(SUBSCRIBE_").append(constName).append(")) {\n");
            sb.append("            svc.addMethod(SUBSCRIBE_").append(constName).append(",\n");
            sb.append("                ServerCalls.asyncBidiStreamingCall(\n");
            sb.append("                    (StreamObserver<").append(qualifiedType).append("> resp) -> {\n");
            sb.append("                        KafkaSubscriber sub = subscriber.get();\n");
            sb.append("                        if (sub == null) {\n");
            sb.append("                            resp.onError(Status.UNAVAILABLE.withDescription(\"Kafka not yet initialized\").asRuntimeException());\n");
            sb.append("                            return noOpObserver();\n");
            sb.append("                        }\n");
            sb.append("                        return new SubscribeHandler<>(sub, TopicRegistry.TOPIC_")
              .append(constName).append(", resp,\n");
            sb.append("                                ").append(qualifiedType).append("::parseFrom);\n");
            sb.append("                    }));\n");
            sb.append("        }\n\n");
        }

        sb.append("    }\n\n");

        // Private noOpObserver helper used by addRemainingLazy
        sb.append("    @SuppressWarnings(\"unchecked\")\n");
        sb.append("    private static <T> StreamObserver<T> noOpObserver() {\n");
        sb.append("        return (StreamObserver<T>) NO_OP;\n");
        sb.append("    }\n\n");
        sb.append("    private static final StreamObserver<Object> NO_OP = new StreamObserver<>() {\n");
        sb.append("        @Override public void onNext(Object v) {}\n");
        sb.append("        @Override public void onError(Throwable t) {}\n");
        sb.append("        @Override public void onCompleted() {}\n");
        sb.append("    };\n");
        sb.append("}\n");

        Path outDir = outputDir.resolve("src/main/java")
                .resolve(svcPkg.replace('.', '/'))
                .resolve("generated");
        Files.createDirectories(outDir);
        Files.writeString(outDir.resolve("TypedEventBusBindings.java"), sb.toString());
    }

    private static String toConstName(String pascalCase) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < pascalCase.length(); i++) {
            char c = pascalCase.charAt(i);
            if (Character.isUpperCase(c) && i > 0) {
                sb.append('_');
            }
            sb.append(Character.toUpperCase(c));
        }
        return sb.toString();
    }
}
